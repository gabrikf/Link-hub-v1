/**
 * True when a changed file must not contribute a technology tag.
 * Backslashes are normalised so a Windows-style path cannot slip past the
 * directory patterns.
 */
export function isGeneratedOrVendored(path: string): boolean {
  const normalized = path.replace(/\\/g, "/");
  return EXCLUDED_PATH_PATTERNS.some(({ pattern }) => pattern.test(normalized));
}

