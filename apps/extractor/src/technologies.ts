/**
 * Whole filenames that identify a technology without an extension. Kept
 * separate from the extension map because these are matched on the basename,
 * not on what follows the last dot.
 */
export const FILENAME_TECHNOLOGY: Readonly<Record<string, string>> = {
  dockerfile: "docker",
  "docker-compose.yml": "docker",
  "docker-compose.yaml": "docker",
  makefile: "make",
  "cmakelists.txt": "cmake",
  gemfile: "ruby",
  rakefile: "ruby",
  "cargo.toml": "rust",
  "go.mod": "go",
  "pyproject.toml": "python",
  "requirements.txt": "python",
  "build.gradle": "gradle",
  "build.gradle.kts": "gradle",
  "pom.xml": "maven",
};

/** The technology a single changed file credits, or null for "nothing". */
export function technologyForPath(path: string): string | null {
  if (isGeneratedOrVendored(path)) return null;

  const normalized = path.replace(/\\/g, "/");
  const basename = (normalized.split("/").pop() ?? "").toLowerCase();
  if (!basename) return null;

  const byName = FILENAME_TECHNOLOGY[basename];
  if (byName) return byName;

  // `Dockerfile.prod` / `Dockerfile.dev` are still Dockerfiles.
  if (basename.startsWith("dockerfile.")) return "docker";

  const dot = basename.lastIndexOf(".");
  if (dot <= 0) return null;
  const extension = basename.slice(dot + 1);
  return EXTENSION_TECHNOLOGY[extension] ?? null;
}

/** The API caps a single event's technology list; see `technologyTagSchema`. */
export const MAX_TECHNOLOGIES_PER_EVENT = 30;

/**
 * The distinct technologies a set of changed files credits, sorted so the same
 * commit always produces byte-identical output (which is what lets a user
 * diff two extractor runs and see nothing changed).
 */
export function inferTechnologies(paths: readonly string[]): string[] {
  const tags = new Set<string>();
  for (const path of paths) {
    const tag = technologyForPath(path);
    if (tag) tags.add(tag);
  }
  return [...tags].sort().slice(0, MAX_TECHNOLOGIES_PER_EVENT);
}
